// —— أدوات اختيار محدَّدة (seeded) ———————————————————————

function hash(input: string): number {
  let h = 0;
  const s = input.trim().toLowerCase();
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h || 1;
}

function pick<T>(arr: T[], seed: number): T {
  return arr[seed % arr.length];
}

// ينتقي n عناصر متميزة بالدوران من الحوض (بدون تكرار)
function pickDistinct<T>(arr: T[], n: number, seed: number): T[] {
  const count = Math.min(n, arr.length);
  const start = seed % arr.length;
  const result: T[] = [];
  for (let i = 0; i < count; i++) {
    result.push(arr[(start + i) % arr.length]);
  }
  return result;
}

// —— الدالة الرئيسية ——————————————————————————————————————

export function generateAutoContent(input: {
  name: string;
  nameEn?: string;
  price?: number;
  brand?: string;
  category?: Category;
}): AutoContent {
  const name = input.name.trim() || "منتجنا";
  const seed = hash(name + "|" + (input.category ?? "عام"));
  const copy = CATEGORY_COPY[input.category ?? "عام"];

  const fill = (template: string) => template.replaceAll("{name}", name);
  const description = fill(pick(copy.descriptions, seed));
  const tagline = fill(pick(copy.taglines, seed + 1));

  const features = pickDistinct(copy.features, 4, seed + 2);

  const testimonials = pickDistinct(TESTIMONIAL_POOL, 3, seed + 3).map((t) => ({
    quote: t.quote.replaceAll("{name}", name).replaceAll("{city}", t.city),
    name: t.person,
    city: t.city,
  }));

  const stats: Stat[] = [
    { value: "58", label: "ولاية توصيل" },
    { value: "24-48س", label: "مدة التوصيل" },
    { value: "COD", label: "الدفع عند الاستلام" },
  ];

  const tags = [
    ...copy.tags,
    ...(input.nameEn ? [input.nameEn] : []),
    "أصلي",
  ];

  return {
    eyebrow: pick(copy.eyebrows, seed + 4),
    tagline,
    badge: "جديد",
    description,
    features,
    testimonials,
    stats,
    tags: Array.from(new Set(tags)).filter(Boolean).slice(0, 5),
  };
}
