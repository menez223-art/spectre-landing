import type { DeliveryPrices, WilayaPrice, WilayaPrices } from "@/app/lib/types";

// أسعار توصيل موحّدة لكل الولايات (بالدينار الجزائري)
export const DELIVERY_PRICES = {
  home: 700, // التوصيل للمنزل
  office: 500, // الاستلام من المكتب
} as const;

// أسعار التوصيل الفعلية — قيم المنتج إن حددها، وإلا القيم الافتراضية
export function deliveryPricesFor(product?: { delivery?: DeliveryPrices }): DeliveryPrices {
  return product?.delivery ?? { home: DELIVERY_PRICES.home, office: DELIVERY_PRICES.office };
}

// جلب خريطة أسعار الولايات لمنتج — فارغة إن لم تُحدَّد أو كان الوضع ثابتاً
export function wilayaPricesFor(product?: {
  deliveryMode?: "fixed" | "wilaya";
  wilayaPrices?: WilayaPrices;
}): WilayaPrices {
  if (!product || product.deliveryMode !== "wilaya" || !product.wilayaPrices) return {};
  return product.wilayaPrices;
}

// يطبّع قيمة خريطة الولايات (رقم مفرد legacy أو زوج {home,office}) إلى زوج
// صريح. الرقم المفرد يُفسَّر كسعر "للمنزل"، ويُسقط "المكتب" للافتراضي.
export function normalizeWilayaEntry(
  entry: WilayaPrice | number | undefined,
  fallbackOffice: number
): WilayaPrice {
  if (typeof entry === "number") {
    return { home: entry, office: fallbackOffice };
  }
  if (entry && typeof entry === "object") {
    return {
      home: Number(entry.home) || 0,
      office: entry.office === undefined ? fallbackOffice : Number(entry.office) || 0,
    };
  }
  return { home: 0, office: fallbackOffice };
}

// يطبّع خريطة أسعار الولايات كاملة إلى أزواج {home,office} صريحة.
export function normalizeWilayaPrices(
  prices: WilayaPrices | undefined,
  fallbackOffice: number
): Record<number, WilayaPrice> {
  const out: Record<number, WilayaPrice> = {};
  if (!prices) return out;
  for (const [code, entry] of Object.entries(prices)) {
    out[Number(code)] = normalizeWilayaEntry(entry, fallbackOffice);
  }
  return out;
}

// هل المنتج يستخدم وضع التوصيل حسب الولاية؟
export function isWilayaMode(product?: {
  deliveryMode?: "fixed" | "wilaya";
}): boolean {
  return product?.deliveryMode === "wilaya";
}

// السعر الفعلي للتوصيل لولاية معيّنة ونوع توصيل محدّد (للمنزل/للمكتب) في وضع wilaya.
// يسقط إلى السعر الافتراضي للنوع المعني عند غياب سعر مخصّص لهذه الولاية.
export function wilayaPriceFor(
  product: { deliveryMode?: "fixed" | "wilaya"; wilayaPrices?: WilayaPrices; delivery?: DeliveryPrices },
  code: number,
  type: DeliveryType,
  fallback?: number
): number {
  if (!isWilayaMode(product)) return fallback ?? (type === "office" ? DELIVERY_PRICES.office : DELIVERY_PRICES.home);
  const entry = product.wilayaPrices?.[code];
  const normalized = normalizeWilayaEntry(entry, product.delivery?.office ?? DELIVERY_PRICES.office);
  if (typeof entry === "number") {
    // قيمة legacy: الرقم هو سعر المنزل؛ المكتب يسقط للافتراضي
    return type === "office"
      ? product.delivery?.office ?? DELIVERY_PRICES.office
      : entry;
  }
  if (normalized.home || normalized.office) {
    return type === "office" ? normalized.office : normalized.home;
  }
  return fallback ?? (type === "office" ? DELIVERY_PRICES.office : DELIVERY_PRICES.home);
}

