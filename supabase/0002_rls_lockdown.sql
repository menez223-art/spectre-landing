-- 0002_rls_lockdown.sql — الإقفال الأمني لجدول kv (البند 3)
-- ------------------------------------------------------------
-- التنفيذ: Supabase Dashboard > SQL Editor > الصق ثم Run (~30 ثانية)
-- الأثر: صفر على الكود الحالي — كل قراءات/كتابات التطبيق تمر عبر
--        الخادم بمفتاح service_role الذي يتجاوز RLS ولا يتأثر.
--
-- لماذا؟
--   جدول kv أُنشئ دون تفعيل RLS، وأدوار anon/authenticated في
--   Supabase تحمل صلاحيات افتراضية على جداول public. اليوم لا يوجد
--   anon key موزّع للعملاء، لكن لو فعّلت Realtime مستقبلاً فسيصبح
--   المفتاح العام في متصفح كل زائر — وبغياب RLS يعني ذلك وصولاً
--   كاملاً لقاعدة البيانات (قراءة/تعديل/حذف: منتجات، أجهزة، حظر،
--   اشتراكات). هذا السكربت يقفل الباب قبل أن يُفتح.
-- ============================================================

-- 1) تفعيل حماية الصفوف: بلا أي سياسات = رفض شامل للعموم
alter table public.kv enable row level security;

-- 2) حزام أمان إضافي: سحب الصلاحيات الافتراضية من أدوار العملاء
revoke all on public.kv from anon;
revoke all on public.kv from authenticated;

-- ملاحظة مستقبلية: عند تفعيل Realtime للعملاء ستحتاج سياسة SELECT
-- ضيقة جداً على مفاتيح محددة فقط — لا تُنشأ إلا عند الحاجة الفعلية.
